"""Task 2 fuzzer driver — emits ``bench/results/fuzzer_report.json``.

Runs the generator + metamorphic + differential pipeline for ``--num-graphs``
seeds, classifies each divergence (real miscompile vs tolerance artifact),
minimizes any failing graph to a minimal reproducer, and writes a single
JSON artifact. The artifact schema is locked by ``test_fuzzer.py`` so docs
can rely on the structure even when zero bugs are found.

Modes:
  --mode ci_seeded   : short deterministic run (default --num-graphs 64).
                       Seed range starts at --seed (default 1234).
                       Used by ``make test-host`` and CI as a gate.
  --mode discovery   : long discovery run (e.g. --num-graphs 10000).
                       Used locally to discover real bugs; commits any
                       minimized repro into firmware/host/fuzz/repros/.

Honesty contract:
  - Bugs found ARE reported. Bugs not found are not invented.
  - The artifact's ``num_real_miscompiles`` is exactly the number of
    minimized failures the run actually produced.
  - The planted-bug test is in ``test_fuzzer.py``, NOT in this driver,
    so the artifact never claims to have caught the planted bug as a
    "real" miscompile.
  - Invalid-graph rejection counts are tracked SEPARATELY from
    equivalence checks so the headline "0 miscompiles" claim stays
    apples-to-apples.
"""

