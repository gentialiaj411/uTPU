# 2. Static cycle invariance under input distributions (no RTL required)
# ---------------------------------------------------------------------------


def test_static_cycles_invariant_across_all_5_input_distributions():
    M, K = 32, 32
    counts = []
    for i, dist in enumerate(DEFAULT_DISTRIBUTIONS):
        rng = np.random.default_rng(20260527 + i)
        x = _draw_input_vector(dist, K, rng)
        case = _compile_program(M, K, x_vector=x)
        static = static_cycles_simulator(case["program"])
        sim = simulate_program_bytes(case["program"], array_size=16)
        counts.append((dist, int(static.total_cycles), int(sim.cycle_count_sequential)))
    static_values = {c[1] for c in counts}
    sim_values = {c[2] for c in counts}
    assert len(static_values) == 1, (
        f"static cycle counts varied across distributions: {counts}"
    )
    assert len(sim_values) == 1, (
        f"simulator cycle counts varied across distributions: {counts}"
    )
    assert static_values == sim_values, (
        f"static disagreed with simulator: static={static_values} sim={sim_values}"
    )


def test_static_cycles_invariant_across_distributions_on_multiple_shapes():
    for M, K in [(32, 32), (32, 64), (64, 32)]:
        counts = set()
        for i, dist in enumerate(DEFAULT_DISTRIBUTIONS):
            rng = np.random.default_rng(20260527 + i)
            x = _draw_input_vector(dist, K, rng)
            case = _compile_program(M, K, x_vector=x)
            counts.add(int(static_cycles_simulator(case["program"]).total_cycles))
        assert len(counts) == 1, (
            f"shape=({M},{K}) static counts varied across distributions: {counts}"
        )


