"""Task 4 tests: static cycle parity + data-independence prover + schema lock.

Validates ``firmware/host/latency_analysis.py`` end-to-end:

1. Static cycle counts match the ISA simulator's accounting byte-exactly
   on the blocked-FC corpus (naive + scheduled lowerings) over a wide
   shape sweep.
2. Mixed / D-type / extended-address synthetic programs round-trip
   through both the simulator and the static walker with identical
   cycle totals — proves the walker's word-advance logic stays in
   lockstep with the simulator across every opcode encoding.
3. The data-independence prover correctly identifies *every* shipping
   opcode as data-independent under the default allowlist AND
   correctly flags a deliberately-excluded opcode under a narrowed
   allowlist (the planted-defect test).
4. The static cycle count is invariant across the 5 adversarial input
   distributions used in the harness for a fixed shape (by
   construction: input data lives in BSTORE payloads, not in opcode
   bits, so the instruction count is shape-determined; this test
   keeps that invariant honest against future regressions in the
   lowering).
5. Schema lock on the committed ``bench/results/latency_determinism.json``
   artifact: required top-level keys present, ``status`` is one of
   the documented values, the static arm reports
   ``exact_match=True`` on every swept shape, ``data_dependent_ops_found``
   is empty, and the static distribution sweep has variance == 0.

Reality floors (gated whenever the artifact is present):
- ``status == "rtl_sim"`` OR ``status == "hardware"`` (no failed-mode
  artifact committed).
- ``static_arm_all_shapes_exact_match == True``.
- ``proof.data_dependent_ops_found == []``.
- ``data_independence[0].static_cycle_invariant == True`` and
  ``static_cycle_variance == 0``.
- If ``rtl_arm`` is present (``iverilog`` was available at regen time):
  ``data_independence[0].rtl_cycle_invariant == True`` and
  ``rtl_cycle_variance == 0``.

The artifact is regenerated by
``python firmware/host/run_latency_determinism.py [--skip-iverilog]``.
"""

