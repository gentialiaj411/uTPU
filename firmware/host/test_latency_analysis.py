# 1. Static cycle parity vs the ISA simulator
# ---------------------------------------------------------------------------


_BLOCKED_FC_SHAPES = [
    (32, 32),
    (32, 64),
    (64, 32),
    (64, 64),
    (128, 32),
    (16, 32),
]


@pytest.mark.parametrize("m,k", _BLOCKED_FC_SHAPES)
def test_static_cycles_match_simulator_blocked_fc_naive(m, k):
    seed = 0xC0DE + m * 31 + k
    rng = np.random.default_rng(seed)
    w = rng.integers(low=-8, high=8, size=(m, k), dtype=np.int8)
    x = rng.integers(low=-8, high=8, size=k, dtype=np.int8)
    naive = lower_blocked_fc_program_utpu(
        w, x, m, k, 16, False, True, 256, 0, 320, prog_depth=1024
    )
    sim = simulate_program_bytes(naive["program"], array_size=16)
    static = static_cycles_simulator(naive["program"])
    assert static.total_cycles == sim.cycle_count_sequential, (
        f"naive shape=({m},{k}): static={static.total_cycles} "
        f"sim={sim.cycle_count_sequential}"
    )
    assert static.halted is True
    sum_per_op = sum(static.per_opcode_cycles.values())
    assert sum_per_op == static.total_cycles, (
        "per_opcode_cycles must sum to total_cycles "
        f"({sum_per_op} != {static.total_cycles})"
    )


