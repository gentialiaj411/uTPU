def test_analyze_program_bundles_static_cycles_and_proof():
    seed = 0xC0DE + 64 * 31 + 32
    rng = np.random.default_rng(seed)
    w = rng.integers(low=-8, high=8, size=(64, 32), dtype=np.int8)
    x = rng.integers(low=-8, high=8, size=32, dtype=np.int8)
