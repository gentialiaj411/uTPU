def test_static_cycles_match_simulator_bstore_and_nop_mixed():
    prog = bytearray()
    prog += encodeStoreValues(0, [1, 2, 3, 4])
    prog += encodeBurstStore(8, [0x1111, 0x2222, 0x3333, 0x4444, 0x5555])
    prog += encodeLoadInputs(0)
    prog += encodeLoadWeights(8)
    prog += encodeRun(
        64, compute_en=True, quantize_en=True, relu_en=False, acc_clear_en=True
    )
    prog += encodeFetch(64, top_half=False)
    prog += encodeNop()
    prog += encodeHalt()
    prog_bytes = bytes(prog)
    sim = simulate_program_bytes(prog_bytes, array_size=4)
    static = static_cycles_simulator(prog_bytes)
    assert static.total_cycles == sim.cycle_count_sequential
    assert static.per_opcode_counts.get("BSTORE") == 1
    assert static.per_opcode_counts.get("NOP") == 1
    assert static.per_opcode_counts.get("HALT") == 1
    # BSTORE cost = 2 + count = 2 + 5 = 7.
    assert static.per_opcode_cycles.get("BSTORE") == 7


def test_static_cycles_match_simulator_dtype_subops():
    prog = bytearray()
    prog += encodePeSelect(0)
    prog += encodeBurstStore(0, [0x1, 0x2, 0x3, 0x4])
    prog += encodeBufferXfer(src_pe=0, dst_pe=1, src_addr=0, dst_addr=10, count=4)
    prog += encodeBarrier(0)
    prog += encodeAccAdd(src_pe=0, dst_pe=1)
    prog += encodePeSelect(1)
    prog += encodeLoadWeights(10)
    prog += encodeHalt()
    prog_bytes = bytes(prog)
    sim = simulate_program_bytes(prog_bytes, num_pe=2, array_size=4)
    static = static_cycles_simulator(prog_bytes)
    assert static.total_cycles == sim.cycle_count_sequential
    for token in ("PE_SELECT", "BSTORE", "BUFFER_XFER", "BARRIER", "ACC_ADD", "HALT"):
        assert token in static.per_opcode_counts, (
            f"{token!r} not in {sorted(static.per_opcode_counts)}"
        )
    # BUFFER_XFER cost = 2 + count = 2 + 4 = 6.
    assert static.per_opcode_cycles.get("BUFFER_XFER") == 6


def test_static_cycles_match_simulator_extended_address_int8():
    cfg = IsaConfig(instruction_width=16, address_width=14, compute_data_width=8)
    prog = bytearray()
    prog += encodeStoreValues(100, [1, 2], cfg=cfg)
    prog += encodeBurstStore(200, [0x1111, 0x2222, 0x3333], cfg=cfg)
    prog += encodeLoadInputs(100, cfg=cfg)
    prog += encodeLoadWeights(200, cfg=cfg)
    prog += encodeRun(
        500,
        compute_en=True,
        quantize_en=True,
        relu_en=False,
        acc_clear_en=True,
        cfg=cfg,
    )
    prog += encodeFetch(500, cfg=cfg)
    prog += encodeHalt(cfg=cfg)
    prog_bytes = bytes(prog)
    sim = simulate_program_bytes(prog_bytes, cfg=cfg, array_size=4)
    static = static_cycles_simulator(prog_bytes, cfg=cfg)
    assert static.total_cycles == sim.cycle_count_sequential


