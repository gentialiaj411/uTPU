"""Build the Boolean board bitstream after the existing implementation flow.

Vivado is deliberately invoked only on an owner's machine with Vivado installed.
--dry-run emits the exact Tcl without invoking Vivado.
"""
from __future__ import annotations
import argparse, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PYTHON = r"C:\Users\bhask\AppData\Local\Programs\Python\Python311\python.exe"
VIVADO = r"C:\AMDDesignTools\2025.2\Vivado\bin\vivado.bat"
PART = "xc7s50csga324-1"
FLASH_OFFSET = 0x280000

def variant(ddr: bool):
    return ("ddr", "boolean_top_ddr") if ddr else ("sdr", "boolean_top")

def parse_reports(out: Path) -> dict:
    timing = (out / "timing.rpt").read_text(errors="replace")
    drc = (out / "drc.rpt").read_text(errors="replace")
    m = re.search(r"WNS\(ns\)\s+TNS\(ns\).*?\n.*?\n\s*(-?[\d.]+)\s+(-?[\d.]+)\s+\d+\s+\d+\s+(-?[\d.]+)\s+(-?[\d.]+)", timing, re.S)
    if not m:
        raise RuntimeError(f"cannot parse timing summary: {out / 'timing.rpt'}")
    wns, tns, whs, ths = map(float, m.groups())
    drc_errors = re.findall(r"^\|\s*(\S+)\s*\|\s*(?:Error|Critical Warning)\s*\|", drc, re.M)
    checks = re.search(r"Checks found:\s*(\d+)", drc)
    result = {"wns_ns": wns, "tns_ns": tns, "whs_ns": whs, "ths_ns": ths,
              "timing_met": wns >= 0 and tns == 0 and whs >= 0 and ths == 0,
              "drc_checks_found": int(checks.group(1)) if checks else None,
              "drc_error_rules": drc_errors}
    if not result["timing_met"] or drc_errors:
        raise RuntimeError(f"refusing write_bitstream: implementation checks failed: {result}")
    return result

def bitstream_tcl(base: Path, out_bit: Path) -> str:
    return (f"# Generated by build_bitstream.py; base flow is tools/board/impl_top.py\n"
            f"source {{{base.as_posix()}}}\n"
            f"set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]\n"
            f"set_property BITSTREAM.CONFIG.CONFIGRATE 26 [current_design]\n"
            f"set_property BITSTREAM.CONFIG.SPI_32BIT_ADDR No [current_design]\n"
            f"set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]\n"
            f"write_bitstream -force {{{out_bit.as_posix()}}}\n")

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ddr", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    name, tag = variant(a.ddr)
    out = ROOT / "build/decode/synth" / tag
    out.mkdir(parents=True, exist_ok=True)
    emit = [PYTHON, str(ROOT / "tools/board/impl_top.py"), *( ["--ddr"] if a.ddr else [] ), "--emit-only"]
    if a.dry_run:
        # The emit-only path is Python-only and does not run Vivado. Importing
        # also keeps dry-run usable in a sandbox where the owner's Python path
        # is intentionally inaccessible.
        import importlib.util
        spec = importlib.util.spec_from_file_location("impl_top_emit", ROOT / "tools/board/impl_top.py")
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
        old_argv = sys.argv
        try:
            sys.argv = [str(ROOT / "tools/board/impl_top.py"), *( ["--ddr"] if a.ddr else [] ), "--emit-only"]
            mod.main()
        finally:
            sys.argv = old_argv
    else:
        subprocess.run(emit, cwd=ROOT, check=True)
        base = out / "run.tcl"
        log = out / "vivado_impl.log"
        with log.open("w") as fh:
            subprocess.run(["cmd", "/c", VIVADO, "-mode", "batch", "-nojournal", "-nolog", "-source", str(base)], cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, check=True)
        reports = parse_reports(out)
        print("implementation checks", reports)
    bit = ROOT / "build/board" / name / "boolean_top.bit"
    bit.parent.mkdir(parents=True, exist_ok=True)
    tcl = ROOT / "build/board" / name / "write_bitstream.tcl"
    tcl.write_text(bitstream_tcl(out / "run.tcl", bit) if a.dry_run or (out / "run.tcl").exists() else "")
    if a.dry_run:
        print(tcl.read_text())
        return 0
    log = tcl.with_suffix(".log")
    with log.open("w") as fh:
        subprocess.run(["cmd", "/c", VIVADO, "-mode", "batch", "-nojournal", "-nolog", "-source", str(tcl)], cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, check=True)
    if not bit.exists():
        raise RuntimeError(f"Vivado completed without {bit}")
    if bit.stat().st_size > FLASH_OFFSET:
        raise RuntimeError(f"bitstream is {bit.stat().st_size} bytes and overlaps weight offset 0x{FLASH_OFFSET:x}")
    print(f"{bit}: {bit.stat().st_size} bytes; clear of weight offset 0x{FLASH_OFFSET:x}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
