"""Build the Boolean board bitstream after the existing implementation flow.

Vivado is deliberately invoked only on an owner's machine with Vivado installed.
--dry-run emits the exact Tcl without invoking Vivado.
"""
from __future__ import annotations
import argparse, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PYTHON = r"C:\Users\bhask\AppData\Local\Programs\Python\Python311\python.exe"
VIVADO = r"C:\AMDDesignTools\2025.2\Vivado\bin\vivado.bat"
PART = "xc7s50csga324-1"
FLASH_OFFSET = 0x280000

def variant(ddr: bool, pruned: bool):
    return ("pruned_ddr", "pruned_ddr") if pruned else (("ddr", "boolean_top_ddr") if ddr else ("sdr", "boolean_top"))

def parse_reports(out: Path) -> dict:
    timing = (out / "timing.rpt").read_text(errors="replace")
    drc = (out / "drc.rpt").read_text(errors="replace")
    m = re.search(r"WNS\(ns\)\s+TNS\(ns\).*?\n.*?\n\s*(-?[\d.]+)\s+(-?[\d.]+)\s+\d+\s+\d+\s+(-?[\d.]+)\s+(-?[\d.]+)", timing, re.S)
    if not m:
        raise RuntimeError(f"cannot parse timing summary: {out / 'timing.rpt'}")
    wns, tns, whs, ths = map(float, m.groups())
    drc_errors = re.findall(r"^\|\s*(\S+)\s*\|\s*(?:Error|Critical Warning)\s*\|", drc, re.M)
    checks = re.search(r"Checks found:\s*(\d+)", drc)
    result = {"wns_ns": wns, "tns_ns": tns, "whs_ns": whs, "ths_ns": ths,
              "timing_met": wns >= 0 and tns == 0 and whs >= 0 and ths == 0,
              "drc_checks_found": int(checks.group(1)) if checks else None,
              "drc_error_rules": drc_errors}
    if not result["timing_met"] or drc_errors:
        raise RuntimeError(f"refusing write_bitstream: implementation checks failed: {result}")
    return result

def bitstream_tcl(dcp: Path, out_bit: Path) -> str:
    """Open the routed design that impl_top.py already checked; never re-implement."""
    return "\n".join([
        "# Generated by build_bitstream.py from the routed checkpoint written by tools/board/impl_top.py",
        f"open_checkpoint {{{dcp.as_posix()}}}",
        "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
        "set_property BITSTREAM.CONFIG.CONFIGRATE 26 [current_design]",
        "set_property BITSTREAM.CONFIG.SPI_32BIT_ADDR No [current_design]",
        "set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]",
        f"write_bitstream -force {{{out_bit.as_posix()}}}", ""])

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ddr", action="store_true")
    ap.add_argument("--pruned", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="print the bitstream Tcl; run nothing")
    ap.add_argument("--skip-impl", action="store_true", help="reuse the last routed.dcp (its reports are still checked)")
    a = ap.parse_args(argv)
    name, tag = variant(a.ddr, a.pruned)
    out = ROOT / "build/decode/synth" / tag
    dcp = out / "routed.dcp"
    bit = ROOT / "build/board" / name / "boolean_top.bit"
    tcl_text = bitstream_tcl(dcp, bit)
    if a.dry_run:
        print(f"# step 1: {PYTHON} tools/board/impl_top.py{' --ddr' if a.ddr or a.pruned else ''}{' --pruned' if a.pruned else ''}")
        print("# step 2 (Vivado batch):")
        print(tcl_text)
        return 0
    if not a.skip_impl:
        # the full implementation flow, including its params.json consistency check and result JSON
        impl_args = ["--ddr", "--pruned"] if a.pruned else (["--ddr"] if a.ddr else [])
        subprocess.run([sys.executable, str(ROOT / "tools/board/impl_top.py"), *impl_args], cwd=ROOT, check=True)
    if not dcp.exists():
        raise RuntimeError(f"no routed checkpoint at {dcp}; run without --skip-impl")
    reports = parse_reports(out)          # raises (refuses) on timing or DRC failure
    print("implementation checks", reports)
    bit.parent.mkdir(parents=True, exist_ok=True)
    if bit.exists():
        bit.unlink()
    tcl = bit.parent / "write_bitstream.tcl"
    tcl.write_text(tcl_text)
    with tcl.with_suffix(".log").open("w") as fh:
        subprocess.run(["cmd", "/c", VIVADO, "-mode", "batch", "-nojournal", "-nolog", "-source", str(tcl)], cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, check=True)
    if not bit.exists():
        raise RuntimeError(f"Vivado completed without {bit}; see {tcl.with_suffix('.log')}")
    if bit.stat().st_size > FLASH_OFFSET:
        raise RuntimeError(f"bitstream is {bit.stat().st_size} bytes and overlaps weight offset 0x{FLASH_OFFSET:x}")
    print(f"{bit}: {bit.stat().st_size} bytes; clear of weight offset 0x{FLASH_OFFSET:x}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
