"""Generate a 16 MiB SPIx4 MCS with the bitstream and 15M weight image."""
from __future__ import annotations
import argparse, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PART = "s25fl128sxxxxxx0-spi-x1_x2_x4"
FLASH_BYTES, WEIGHT_OFFSET = 16 * 1024 * 1024, 0x280000

def make_tcl(bitstream: Path, weights: Path, out: Path) -> str:
    return (f"# Generated by make_flash_image.py\n"
            f"write_cfgmem -force -format MCS -size 16 -interface SPIx4 "
            # [list ...] so a path is one Tcl word without literal braces ("up 0x0 {p}" passes the braces into the filename)
            f"-loadbit [list up 0x0 {{{bitstream.as_posix()}}}] "
            f"-loaddata [list up 0x{WEIGHT_OFFSET:x} {{{weights.as_posix()}}}] "
            f"-file {{{out.as_posix()}}}\n")

def byte_map(bitstream: Path, weights: Path):
    b, w = bitstream.stat().st_size, weights.stat().st_size
    if b > WEIGHT_OFFSET:
        raise ValueError(f"bitstream {b} bytes overlaps weights at 0x{WEIGHT_OFFSET:x}")
    if WEIGHT_OFFSET + w > FLASH_BYTES:
        raise ValueError(f"weights end at 0x{WEIGHT_OFFSET+w:x}, beyond 16 MiB flash")
    return [("bitstream", 0, b), ("weights", WEIGHT_OFFSET, WEIGHT_OFFSET + w)]

def read_mcs(path: Path) -> dict[int, int]:
    """Intel HEX (Vivado MCS) -> {address: byte}; checks every record checksum."""
    mem, base = {}, 0
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if not line.startswith(":"): raise ValueError(f"{path}:{n}: not an Intel HEX record")
        rec = bytes.fromhex(line[1:])
        if sum(rec) & 0xFF: raise ValueError(f"{path}:{n}: bad checksum")
        count, addr, rtype, data = rec[0], int.from_bytes(rec[1:3], "big"), rec[3], rec[4:4 + rec[0]]
        if rtype == 0x00:
            for i, b in enumerate(data): mem[base + addr + i] = b
        elif rtype == 0x04: base = int.from_bytes(data, "big") << 16
        elif rtype == 0x01: break
    return mem

def bit_payload(bitstream: Path) -> bytes:
    """Configuration data of a .bit: from the first 0xFF dummy pad before the AA995566 sync word to the end."""
    raw = bitstream.read_bytes()
    sync = raw.find(bytes.fromhex("AA995566"))
    if sync < 0: raise ValueError(f"{bitstream}: no sync word")
    start = sync
    while start > 0 and raw[start - 1] in (0xFF, 0x00, 0xBB, 0x11, 0x22, 0x44): start -= 1
    return raw[start:]

def verify_mcs(mcs: Path, bitstream: Path, weights: Path) -> dict:
    """The programmed flash must hold the weight image byte-for-byte at WEIGHT_OFFSET and the bitstream's
    sync word + configuration data starting near 0x0. Raises on any mismatch."""
    mem = read_mcs(mcs)
    w = weights.read_bytes()
    bad = [i for i in range(len(w)) if mem.get(WEIGHT_OFFSET + i) != w[i]]
    if bad:
        i = bad[0]
        raise ValueError(f"MCS weights differ from {weights.name} at {len(bad)} bytes; first at 0x{WEIGHT_OFFSET+i:x}: "
                         f"mcs {mem.get(WEIGHT_OFFSET+i)} vs image {w[i]}")
    stray = [a for a in mem if a >= WEIGHT_OFFSET + len(w)]
    if stray: raise ValueError(f"MCS has {len(stray)} bytes past the end of the weights (first 0x{min(stray):x})")
    payload = bit_payload(bitstream)
    sync_off = payload.find(bytes.fromhex("AA995566"))
    flash_lo = bytes(mem.get(a, 0xFF) for a in range(0, len(payload) + 256))
    at = flash_lo.find(payload[sync_off:])
    if at < 0:
        raise ValueError("MCS does not contain the bitstream configuration data (from the sync word on) below the weights")
    top = max(a for a in mem if a < WEIGHT_OFFSET)
    if top >= WEIGHT_OFFSET: raise ValueError("bitstream region overlaps weights")
    return {"weights_bytes_verified": len(w), "bitstream_sync_at": at, "bitstream_bytes_verified": len(payload) - sync_off,
            "bitstream_end": top + 1, "bytes_past_weights": len(stray)}

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ddr", action="store_true")
    ap.add_argument("--pruned", action="store_true")
    ap.add_argument("--bitstream", type=Path)
    ap.add_argument("--weights", type=Path, default=ROOT / "build/decode/decode_image_15m/image.bin")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--vivado", default=r"C:\AMDDesignTools\2025.2\Vivado\bin\vivado.bat")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    name = "pruned_ddr" if a.pruned else "ddr" if a.ddr else "sdr"
    bit = a.bitstream or ROOT / "build/board" / name / "boolean_top.bit"
    out = a.out or ROOT / "build/board" / name / "boolean_top.mcs"
    if a.pruned and a.weights == ROOT / "build/decode/decode_image_15m/image.bin":
        a.weights = ROOT / "build/vocabprune/vocab_8192.image.bin"
    bit, weights, out = map(lambda p: p.resolve(), (bit, a.weights, out))
    if not bit.exists(): raise FileNotFoundError(bit)
    if not weights.exists(): raise FileNotFoundError(f"{weights}; run tools/decode/pack_decode_image.py --model 15m first")
    rows = byte_map(bit, weights)
    print(f"cfgmem part: {PART}; flash: {FLASH_BYTES} bytes")
    for label, start, end in rows: print(f"{label}: 0x{start:08x}..0x{end:08x} ({end-start} bytes)")
    tcl = out.with_suffix(".tcl"); tcl.parent.mkdir(parents=True, exist_ok=True); tcl.write_text(make_tcl(bit, weights, out))
    if a.dry_run:
        print(tcl.read_text()); return 0
    if out.exists(): out.unlink()
    subprocess.run(["cmd", "/c", a.vivado, "-mode", "batch", "-nojournal", "-nolog", "-source", str(tcl)], cwd=ROOT, check=True)
    print("verified:", verify_mcs(out, bit, weights))
    return 0

if __name__ == "__main__": raise SystemExit(main())
